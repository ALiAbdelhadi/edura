/**
 * The service worker's push/click decisions, as pure functions.
 *
 * They live outside `sw.ts` because nothing inside a service worker is
 * reachable from a test: the worker global scope cannot be constructed, so
 * every line written directly against `self` is shipped unproven. These
 * functions take plain values and return plain decisions, so the two rules that
 * actually matter — what a push renders, and where a click lands — are held by
 * `tests/unit/sw-handlers.test.ts` instead of by hand-testing on a phone.
 *
 * Structurally typed on purpose (no `ServiceWorkerGlobalScope`, no `DOM` types):
 * the file is type-checked twice, once under `lib: WebWorker` for the worker and
 * once under `lib: dom` with the rest of the app, and the two lib sets do not
 * agree on what a client is.
 */

export type PushPayload = {
  title?: string;
  body?: string;
  url?: string;
  data?: Record<string, string>;
};

/** The subset of `PushMessageData` this worker reads. */
export type PushData = { json: () => unknown; text: () => string };

export const DEFAULT_TITLE = "Edura";
export const DEFAULT_URL = "/";

/**
 * PNG, not SVG — Chrome on Android renders neither an SVG `icon` nor an SVG
 * `badge`, and shows its own generic glyph instead with no warning. Both point
 * at `/edura-mark.svg` in the version of this worker deployed today, so every
 * push on the platform this product is built for arrives unbranded.
 *
 * Generated by `bun run gen:icons` from the one shared geometry.
 * The icon carries a paper ground so ink strokes survive a dark notification
 * shade; the badge is alpha-only, because Android discards its colour.
 */
export const NOTIFICATION_ICON = "/notification-icon.png";
export const NOTIFICATION_BADGE = "/notification-badge.png";

/**
 * A push body is attacker-adjacent input in the ordinary sense that it arrives
 * over the network and may be malformed: parse defensively, never throw. A
 * worker that throws inside `push` shows the browser's own "This site has been
 * updated in the background" notice instead of the message.
 */
export function parsePushPayload(data: PushData | null | undefined): PushPayload {
  if (!data) return {};
  try {
    const parsed = data.json();
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
      return parsed as PushPayload;
    }
    return { body: String(parsed) };
  } catch {
    try {
      const text = data.text();
      return text ? { body: text } : {};
    } catch {
      return {};
    }
  }
}

export type NotificationSpec = {
  title: string;
  options: {
    body?: string;
    icon: string;
    badge: string;
    data: { url: string };
  };
};

export function notificationSpec(payload: PushPayload): NotificationSpec {
  return {
    title: payload.title ?? DEFAULT_TITLE,
    options: {
      body: payload.body,
      icon: NOTIFICATION_ICON,
      badge: NOTIFICATION_BADGE,
      // The URL travels on the notification itself, because the click that
      // consumes it happens in a later event with no access to this payload.
      data: { url: payload.url ?? payload.data?.url ?? DEFAULT_URL },
    },
  };
}

export type ClickTarget =
  /** A tab is already showing this exact page — just bring it forward. */
  | { action: "focus"; index: number; url: string }
  /** A tab is open on this app — move it to the notification's page. */
  | { action: "navigate"; index: number; url: string }
  /** Nothing is open — open a window on the notification's page. */
  | { action: "open"; url: string };

/**
 * A client's URL is ABSOLUTE (`WindowClient.url` always is), so it is parsed
 * without a base: resolving it against the origin instead would turn any
 * unparseable value into a same-origin path and hand the click to a tab that
 * is not ours. The target URL is the opposite — it is ours and it is relative.
 */
function parseClient(clientUrl: string): URL | null {
  try {
    return new URL(clientUrl);
  } catch {
    return null;
  }
}

function samePage(clientUrl: string, targetUrl: string, origin: string): boolean {
  const a = parseClient(clientUrl);
  if (!a) return false;
  try {
    const b = new URL(targetUrl, origin);
    return a.origin === b.origin && a.pathname === b.pathname;
  } catch {
    return false;
  }
}

function sameOrigin(clientUrl: string, origin: string): boolean {
  const a = parseClient(clientUrl);
  return a !== null && a.origin === origin;
}

/**
 * Where a notification click goes.
 *
 * THE BUG THIS EXISTS TO PREVENT: the previous handler focused any open tab and
 * returned, discarding the URL entirely. With the app open — the normal case on
 * a phone, where the PWA is the tab — every notification "worked" (the app came
 * forward) and none of them arrived: an absence notification left the reader on
 * whatever page they had been looking at, with nothing to say a click had been
 * registered at all.
 *
 * `focus` before `navigate` is not an optimisation either: navigating a client
 * that is already on the page would reload it and throw away whatever the
 * reader had typed or scrolled to.
 */
export function resolveClickTarget(
  url: string,
  clients: readonly { url: string }[],
  origin: string,
): ClickTarget {
  const already = clients.findIndex((c) => samePage(c.url, url, origin));
  if (already !== -1) return { action: "focus", index: already, url };

  const open = clients.findIndex((c) => sameOrigin(c.url, origin));
  if (open !== -1) return { action: "navigate", index: open, url };

  return { action: "open", url };
}
