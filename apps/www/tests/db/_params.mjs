export function concrete(app, path) {
  if (!path.includes("[")) return path;
  const key = path;
  const p = PARAMS[key];
  let out = path;
  out = out.replace(/\[\.\.\.([^\]]+)\]/g, (_m, n) => (p && p["..." + n]) || "session");
  out = out.replace(/\[([^\]]+)\]/g, (_m, n) => (p && p[n]) || RANDOM_UUID);
  return out;
}

