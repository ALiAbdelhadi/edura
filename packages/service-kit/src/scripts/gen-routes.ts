// Writes <root>/index.ts from the route files under <root> (a service's
// `src/routes`). Each `<root>/<p>/route.ts` serves `/api/<p>`, the same path its
// Next file had under the frontend's `src/app/api`. A service's own
// scripts/gen-routes.ts calls this with its routes folder; run it after adding
// or removing a route file:
//   bun scripts/gen-routes.ts          (write)
//   bun scripts/gen-routes.ts --check  (exit 1 if index.ts is stale)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return name === "route.ts" ? [full] : [];
  });
}

// Hono answers with the first registered route that matches; Next tries a
// fixed segment before a dynamic one, and a dynamic one before a catch-all.
// Plain string order puts `[` before letters, so `payments/[id]` would shadow
// `payments/initiate`. Order segment by segment the way Next resolves them.
function segmentRank(seg: string): number {
  if (seg.startsWith("[...")) return 2;
  return seg.startsWith("[") ? 1 : 0;
}

export function compareRoutes(a: string, b: string): number {
  const as = a.split("/");
  const bs = b.split("/");
  for (let i = 0; i < Math.min(as.length, bs.length); i++) {
    const rank = segmentRank(as[i]!) - segmentRank(bs[i]!);
    if (rank !== 0) return rank;
    if (as[i] !== bs[i]) return as[i]! < bs[i]! ? -1 : 1;
  }
  return as.length - bs.length;
}

export type GenRoutesOptions = {
  // The module the generated index takes `RouteEntry` from. A service that keeps
  // a `routes/mount.ts` re-export uses the default.
  mountImport?: string;
};

// The text of <root>/index.ts and the number of routes in it.
export function routesIndex(root: string, opts: GenRoutesOptions = {}): { text: string; count: number } {
  const files = walk(root)
    .map((f) => relative(root, f).split(sep).slice(0, -1).join("/"))
    .sort(compareRoutes);

  const lines = [
    "// GENERATED by scripts/gen-routes.ts — do not edit by hand.",
    `import type { RouteEntry } from "${opts.mountImport ?? "./mount"}";`,
    ...files.map((dir, i) => `import * as r${i} from "./${dir}/route";`),
    "",
    "export const ROUTES: readonly RouteEntry[] = [",
    ...files.map((dir, i) => `  { path: "/api/${dir}", module: r${i} },`),
    "];",
    "",
  ];
  return { text: lines.join("\n"), count: files.length };
}

// The script body: writes the index, or with `--check` in `argv` exits 1 when
// the index on disk is stale.
export function runGenRoutes(root: string, argv: readonly string[] = process.argv, opts: GenRoutesOptions = {}): void {
  const out = join(root, "index.ts");
  const { text, count } = routesIndex(root, opts);

  if (argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {
      // no index yet: stale
    }
    if (current !== text) {
      console.error("src/routes/index.ts is stale — run: bun scripts/gen-routes.ts");
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`routes: ${count}`);
  }
}
